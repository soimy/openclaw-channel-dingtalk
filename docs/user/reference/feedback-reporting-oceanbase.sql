-- Reference DDL for OceanBase 4.2.5.7, MySQL-compatible tenant.
-- Run through the company's normal migration process. Not run against production.
CREATE TABLE ai_reply_feedback (
  record_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tenant_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  instance_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  account_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  card_id VARCHAR(200) COLLATE utf8mb4_bin NOT NULL,
  questioner_user_id VARCHAR(256) COLLATE utf8mb4_bin NOT NULL,
  revision BIGINT NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  vote VARCHAR(16) NOT NULL,
  reasons_json TEXT NOT NULL,
  agent_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
  session_key VARCHAR(1024) COLLATE utf8mb4_bin NOT NULL,
  session_id VARCHAR(256) COLLATE utf8mb4_bin NULL,
  question_message_id VARCHAR(256) COLLATE utf8mb4_bin NULL,
  answer_message_id VARCHAR(256) COLLATE utf8mb4_bin NULL,
  conversation_json MEDIUMTEXT NOT NULL,
  answer_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  content_status VARCHAR(16) NOT NULL,
  content_reason VARCHAR(128) NULL,
  question_text MEDIUMTEXT NULL,
  answer_text MEDIUMTEXT NULL,
  created_at_ms BIGINT NOT NULL,
  completed_at_ms BIGINT NULL,
  feedback_at_ms BIGINT NOT NULL,
  received_at_ms BIGINT NOT NULL,
  PRIMARY KEY (record_id),
  UNIQUE KEY uk_source_card (tenant_id, instance_id, account_id, card_id),
  KEY idx_tenant_vote_time (tenant_id, vote, feedback_at_ms),
  KEY idx_instance_time (tenant_id, instance_id, feedback_at_ms)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;

-- Receiver transaction (parameterized SQL; never interpolate request text):
-- 1. Authenticate source; validate protocol/identity/hash BEFORE entering a transaction.
-- 2. START TRANSACTION;
-- 3. SELECT ... FROM ai_reply_feedback WHERE record_id = ? FOR UPDATE;
-- 4. Absent: reject content.mode='preserve' with HTTP 409; otherwise INSERT validated snapshot. A concurrent unique-key conflict must roll
--    back and retry the transaction, not acknowledge an uncommitted insert.
-- 5. Present: verify immutable identity; lower revision => stale; same revision
--    + same request_hash => duplicate; same revision + different hash => conflict.
-- 6. Higher revision: UPDATE current vote/reasons/version/time. For content.mode
--    = 'preserve', retain existing content columns; never set them to NULL.
--    A verified available body must not be overwritten by pending/missing data.
-- 7. COMMIT;
-- 8. Only after successful COMMIT return the protocol acknowledgement.
-- No arithmetic vote counters: query vote IN ('like','dislike'); 'none' is withdrawn.
-- This DDL is a reference; actual 4.2.5.7 execution requires company-side validation.

-- Full field semantics and complete examples: feedback-reporting-api.md.
-- request_hash = SHA-256 of the original UTF-8 HTTP request body bytes, not
-- answer_hash; do not reserialize JSON differently across retries or nodes.
-- Preserve immutable source/card/questioner/conversation/transcript identities,
-- answer_hash, created_at_ms and completed_at_ms across revisions.
-- received_at_ms is generated by the receiver, not supplied in the request.
-- Local expiry does not request central-row deletion; set server retention separately.
